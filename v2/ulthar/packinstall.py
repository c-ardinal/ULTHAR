"""`ulthar pack install --agents-dir <dir>` / `ulthar pack list` (SKL-03, R1-d AC-2), CLI only.

install: for every pack of `.claude/ulthar.json` (validated by ulthar.packs.load), writes
`<dir>/ulthar-creator@<pack>.md` and `<dir>/ulthar-evaluator@<pack>.md` (frontmatter
`skills:` lists every skill of the pack, comma-separated -- P-20), creating <dir> first
(P-13: a definition is usable from the next session only when its directory existed
when the session started), and registers in runtime.db `pack_agents` each file's
sha256 with the path and sha256 of every SKILL.md it lists. SubagentStart compares
those values (AC-4). Only the CLI writes them. Generated files are rewritten on every
install; editing one by hand voids its agents' receipts until the next install.
"""
from __future__ import annotations

import json
import os
from pathlib import Path

from . import flow
from . import packs as packs_mod
from . import stages
from . import store as store_mod

CREATOR_BODY = """You are the ULTHAR creator of the "{pack}" skill pack. Your preloaded skills ({skills})
are the rules for every path of this pack ({globs}); follow them for each change.
Work only on the unit named in your prompt and only inside its confirmed contract's scope.
Write files with Edit / Write / MultiEdit / NotebookEdit; run a file-changing command only
as `ulthar run <unit> <name>` with a name the contract's write_cmds declares -- any other
change is unattributed at integration. Check your work with `ulthar verify <unit> --self`.
"""
EVALUATOR_BODY = """You are the ULTHAR evaluator of the "{pack}" skill pack. Your preloaded skills ({skills})
are the standard the pack's paths ({globs}) are judged by. You never write product files.
Run `ulthar verify <unit>`, then record the result with
`ulthar review record --unit <unit> --kind verify --result pass|fail [--blocker <text>]...`.
Check each item:
{checklist}
"""


def render(role: str, pack: dict, raw_globs: list[str]) -> str:
    name = packs_mod.agent_type(role, pack["name"])
    skills = ", ".join(pack["skills"])
    body = (CREATOR_BODY if role == "creator" else EVALUATOR_BODY).format(
        pack=pack["name"], skills=skills, globs=", ".join(raw_globs),
        checklist="\n".join(f"- {c}" for c in pack["evaluator_checklist"]))
    return (f"---\nname: {name}\ndescription: ULTHAR {role} of the {pack['name']} skill pack, "
            "generated by ulthar pack install (do not edit by hand)\n"
            f"skills: {skills}\n---\n{body}")


def _write(path: Path, text: str) -> bytes:
    data = text.encode("utf-8")
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_bytes(data)
    os.replace(tmp, path)
    return data


def install(store: store_mod.Store, rt, agents_dir: Path) -> list[dict]:
    packs = stages.project_packs(store)
    if not packs:
        raise flow.FlowError(".claude/ulthar.json defines no packs: nothing to install")
    raw = {p["name"]: p["path_globs"] for p in store.config.get("packs") or []}
    agents_dir.mkdir(parents=True, exist_ok=True)
    rows, now = [], store_mod.now_iso()
    for pack in packs:
        skills = []
        for name in pack["skills"]:
            path = packs_mod.skill_file(name, store.repo).resolve()
            skills.append({"name": name, "path": str(path), "sha": packs_mod.file_sha(path)})
        for role in packs_mod.ROLES:
            kind = packs_mod.agent_type(role, pack["name"])
            path = (agents_dir / f"{kind}.md").resolve()
            data = _write(path, render(role, pack, raw[pack["name"]]))
            rows.append({"agent_type": kind, "pack": pack["name"], "role": role,
                         "def_path": str(path), "def_sha": store_mod.sha256(data).hexdigest(),
                         "skills": skills})
    rt.execute("BEGIN IMMEDIATE")
    try:
        for r in rows:
            rt.execute("INSERT OR REPLACE INTO pack_agents (agent_type, project_id, pack, role,"
                       " def_path, def_sha, skills, ts) VALUES (?,?,?,?,?,?,?,?)",
                       (r["agent_type"], store.project_id, r["pack"], r["role"], r["def_path"],
                        r["def_sha"], json.dumps(r["skills"]), now))
        rt.execute("COMMIT")
    except BaseException:
        rt.execute("ROLLBACK")
        raise
    return rows


def listing(rt) -> list[dict]:
    """Every registered pack agent, with whether its files still hash as registered."""
    out = []
    for kind, pack, role, path, sha, skills in rt.execute(
            "SELECT agent_type, pack, role, def_path, def_sha, skills FROM pack_agents"
            " ORDER BY agent_type"):
        skills = json.loads(skills)
        intact = packs_mod.file_sha(path) == sha and all(
            packs_mod.file_sha(s["path"]) == s["sha"] for s in skills)
        out.append({"agent_type": kind, "pack": pack, "role": role, "def_path": path,
                    "skills": [s["name"] for s in skills], "intact": intact})
    return out
